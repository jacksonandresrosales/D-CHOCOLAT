// Primero los de la misma categoría, luego los de porcentaje de cacao más parecido.
export function relacionados(p, n = 3) {
  return PRODUCTOS.filter((o) => o.id !== p.id)
    .map((o) => ({ o, d: (o.cat === p.cat ? 0 : 100) + Math.abs(o.pct - p.pct) }))
    .sort((a, b) => a.d - b.d)
    .slice(0, n)
    .map(({ o }) => o)
}
